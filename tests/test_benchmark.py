import unittest

from doneproof.benchmark import CASES, _count_proposed_and_actionable_checks, compute_live_metrics, load_live_corpus, run_benchmark, run_live_benchmark
from doneproof.login_fixture import MUTANT_IDS


class BenchmarkTests(unittest.TestCase):
    def test_reference_cases_match_expected_mutant_sets_and_scores(self):
        report = run_benchmark()

        self.assertEqual(report["summary"]["case_count"], 4)
        self.assertEqual(report["summary"]["expectations_met"], 4)
        self.assertEqual(report["summary"]["expectations_failed"], 0)
        self.assertTrue(report["summary"]["all_expected_outcomes_matched"])

        expected_by_case = {
            case.case_id: (
                case.expected_killed_mutants,
                round(100.0 * len(case.expected_killed_mutants) / len(MUTANT_IDS), 2),
            )
            for case in CASES
        }
        for result in report["results"]:
            with self.subTest(case_id=result["case_id"]):
                expected_mutants, expected_score = expected_by_case[
                    result["case_id"]
                ]
                self.assertTrue(result["baseline_passed"])
                self.assertTrue(result["matches_expected"])
                self.assertEqual(
                    result["mutation_score_percent"],
                    expected_score,
                )

                expected_killed = [
                    mutant_id
                    for mutant_id in MUTANT_IDS
                    if mutant_id in expected_mutants
                ]
                self.assertEqual(result["actual_killed_mutants"], expected_killed)
                self.assertEqual(
                    result["escaped_mutants"],
                    [
                        mutant_id
                        for mutant_id in MUTANT_IDS
                        if mutant_id not in expected_killed
                    ],
                )

    def test_report_is_repeatable(self):
        self.assertEqual(run_benchmark(), run_benchmark())

    def test_report_states_scope_and_limitations(self):
        report = run_benchmark()

        self.assertEqual(report["benchmark_id"], "doneproof-login-reference-v1")
        self.assertIn("one predefined login fixture", report["scope"])
        self.assertTrue(
            any("not generated by Gemma" in item for item in report["limitations"])
        )

    def test_live_metric_calculation_uses_explicit_denominators(self):
        metrics = compute_live_metrics(
            repeats=2, valid_plans=1, actionable_checks=2, proposed_checks=3,
            scenario_count=5, selected_scenarios=2,
            mutant_kills=2, mutant_trials=4,
            false_positive_checks=1, baseline_checks=2,
            latencies_ms=[100.0, 300.0],
            token_usage={"prompt_tokens": 50, "candidate_tokens": 20, "total_tokens": 70},
            usage_field_runs={"prompt_tokens": 0, "candidate_tokens": 0, "total_tokens": 0},
            usage_runs=0,
        )
        self.assertEqual(metrics["plan_schema_valid_rate_percent"], 50)
        self.assertEqual(metrics["actionable_scenario_rate_percent"], 66.67)
        self.assertEqual(metrics["mean_scenario_coverage_percent"], 40)
        self.assertEqual(metrics["defect_detection_rate_percent"], 50)
        self.assertEqual(metrics["false_positive_rate_percent"], 50)
        self.assertEqual(metrics["execution_failure_rate_percent"], 50)
        self.assertEqual(metrics["mean_latency_ms"], 200)
        self.assertTrue(metrics["usage"]["total_is_partial"])
        self.assertIsNone(metrics["usage"]["total_tokens"])

    def test_versioned_live_corpus_matches_fixture(self):
        corpus = load_live_corpus()
        self.assertEqual(corpus["fixture_id"], "login-auth-v1")
        self.assertEqual(len(corpus["oracle"]["expected_scenarios"]), 5)

    def test_live_benchmark_requires_a_real_api_key_before_provider_use(self):
        import os
        from unittest.mock import patch
        with patch.dict(os.environ, {}, clear=True):
            with self.assertRaisesRegex(RuntimeError, "live evaluation requires a real API key"):
                run_live_benchmark(repeats=1)

    def test_actionable_rate_counts_only_allowlisted_unique_scenarios(self):
        raw = '{"checks":[{"kind":"behavioral_scenario","scenario_id":"wrong_password"},{"kind":"behavioral_scenario","scenario_id":"wrong_password"},{"kind":"execute_shell","scenario_id":"inactive_account"}]}'
        self.assertEqual(_count_proposed_and_actionable_checks(raw), (3, 1))
        self.assertEqual(_count_proposed_and_actionable_checks("not json"), (0, 0))


if __name__ == "__main__":
    unittest.main()
